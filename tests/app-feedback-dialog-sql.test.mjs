import test from 'node:test'
import assert from 'node:assert/strict'
import {readFile} from 'node:fs/promises'
import {randomUUID} from 'node:crypto'

test('feedback SQL preserves history and enforces private, multi-turn, idempotent dialogs and persistent unread cursors',{skip:!process.env.SIMKOLL_PGLITE_MODULE},async t=>{
  const {PGlite}=await import(process.env.SIMKOLL_PGLITE_MODULE),db=new PGlite()
  const swimmer=randomUUID(),other=randomUUID(),admin=randomUUID(),admin2=randomUUID(),coach=randomUUID()
  const call=async(action,options={})=>{
    const p={actor:'admin',id:null,content:null,requestId:null,through:null,before:null,...options}
    const profiles={swimmer,other},coaches={admin,admin2,coach}
    return (await db.query('select public.app_feedback_dialog($1,$2::uuid,$3::uuid,$4::integer,$5::bigint,$6::uuid,$7,$8::bigint,$9::bigint) as data',[action,profiles[p.actor]||null,coaches[p.actor]||null,p.version??2,p.id,p.requestId,p.content,p.through,p.before])).rows[0].data
  }
  try{
    await db.exec(`create role anon;create role authenticated;create role service_role bypassrls;
      create table profiles(id uuid primary key,display_name text,emoji text,active boolean,approval_status text);
      create table coach_accounts(id uuid primary key,role text,status text,session_version integer);
      create table app_feedback(id bigint generated by default as identity primary key,profile_id uuid references profiles(id) on delete set null,submitted_by_role text,comment text,workflow_status text default 'new',archived_at timestamptz,created_at timestamptz default now(),admin_note text,admin_reply text,admin_reply_sent_at timestamptz);
      insert into profiles values('${swimmer}','Tova','🐬',true,'approved'),('${other}','Annan','🙂',true,'approved');
      insert into coach_accounts values('${admin}','superadmin','active',2),('${admin2}','superadmin','active',2),('${coach}','head_coach','active',2);
      insert into app_feedback(id,profile_id,submitted_by_role,comment,admin_note,admin_reply,admin_reply_sent_at) values
       (1,'${swimmer}','swimmer','Plugg i planeringen','HEMLIG INTERN ANTECKNING','Gammalt svar',now()-interval '1 day'),
       (2,'${other}','swimmer','Annan feedback','ANNAN INTERN ANTECKNING',null,null),
       (3,null,'coach','Tränarfeedback',null,null,null);`)
    await db.exec(await readFile(new URL('../supabase/migrations/130_app_feedback_dialog.sql',import.meta.url),'utf8'))
    await t.test('legacy reply retained once, internal comments never returned and own list cannot expose others',async()=>{
      const own=await call('list',{actor:'swimmer'})
      assert.equal(own.items.length,1);assert.equal(own.items[0].id,'1');assert.equal(own.unreadCount,1)
      const thread=await call('thread',{actor:'swimmer',id:1})
      assert.equal((await db.query('select admin_note from app_feedback where id=1')).rows[0].admin_note,'HEMLIG INTERN ANTECKNING')
      assert.equal(thread.messages.length,1);assert.equal(thread.messages[0].content,'Gammalt svar')
      assert(!JSON.stringify(thread).includes('HEMLIG'));assert(!JSON.stringify(own).includes('ANNAN'))
      await assert.rejects(call('thread',{actor:'other',id:1}),/not found/)
      await assert.rejects(call('send',{actor:'other',id:1,requestId:randomUUID(),content:'Otillåtet'}),/not found/)
      assert.equal((await call('count')).unreadCount,2)
    })
    let cursor
    await t.test('multiple turns, duplicate retry and another follow-up preserve all messages',async()=>{
      const requestId=randomUUID()
      const first=await call('send',{id:1,requestId,content:'Vad menar du med pluggdag?'})
      assert(first.created)
      assert.equal((await call('send',{id:1,requestId,content:'Vad menar du med pluggdag?'})).created,false)
      await assert.rejects(call('send',{id:1,requestId,content:'Ändrat innehåll'}),/reused/)
      await call('send',{actor:'swimmer',id:1,requestId:randomUUID(),content:'Jag menar att planera tid. Kan det få en egen ruta?'})
      await call('send',{id:1,requestId:randomUUID(),content:'Ja, vilken sorts markering vill du ha?'})
      const thread=await call('thread',{actor:'swimmer',id:1})
      assert.equal(thread.messages.length,4);assert.equal(thread.messages[2].role,'swimmer')
      cursor=thread.readThrough
    })
    await t.test('list reads never clear unread; delayed acknowledgements cannot consume a newer response or regress',async()=>{
      assert.equal((await call('list',{actor:'swimmer'})).unreadCount,1)
      await call('send',{id:1,requestId:randomUUID(),content:'En ytterligare följdfråga'})
      await call('read',{actor:'swimmer',id:1,through:cursor})
      assert.equal((await call('count',{actor:'swimmer'})).unreadCount,1)
      const thread=await call('thread',{actor:'swimmer',id:1})
      await call('read',{actor:'swimmer',id:1,through:thread.readThrough})
      await call('read',{actor:'swimmer',id:1,through:'0'})
      assert.equal((await call('count',{actor:'swimmer'})).unreadCount,0)
      await assert.rejects(call('read',{actor:'swimmer',id:1,through:'999999'}),/Invalid read/)
      await call('read',{id:1,through:thread.readThrough})
      assert.equal((await call('unread')).items.length,1)
      assert.equal((await call('count',{actor:'admin2'})).unreadCount,2,'read state is per administrator')
    })
    await t.test('all counts precede pagination; replies to an old archived suggestion still surface as unread',async()=>{
      await db.exec(`insert into app_feedback(id,profile_id,submitted_by_role,comment) select n,'${other}','swimmer','Nyare förslag' from generate_series(4,70) n; update app_feedback set archived_at=now(),workflow_status='completed' where id=1;`)
      await call('send',{actor:'swimmer',id:1,requestId:randomUUID(),content:'Kan jag fråga en sak till?'})
      assert.equal((await call('count')).unreadCount,69)
      await db.exec(`insert into app_feedback_reads select id,'superadmin','${admin}',0 from app_feedback where id>=4;`)
      assert((await call('unread')).items.some(row=>row.id==='1'&&row.archived))
      const first=await call('list');assert.equal(first.items.length,30)
      const second=await call('list',{before:first.nextBefore});assert.equal(second.items.length,30)
      assert(!second.items.some(row=>first.items.some(one=>one.id===row.id)))
      assert.equal((await call('thread',{id:1})).status,'completed','dialog does not rewrite workflow state')
    })
    await t.test('history pagination has no clipped or repeated messages; direct access and revoked sessions fail closed',async()=>{
      await db.exec(`insert into app_feedback_messages(feedback_id,author_role,author_id,request_id,content) select 1,'swimmer','${swimmer}',gen_random_uuid(),'Historik '||n from generate_series(1,110) n;`)
      const page=await call('thread',{actor:'swimmer',id:1});assert.equal(page.messages.length,50);assert(page.olderBefore)
      const older=await call('thread',{actor:'swimmer',id:1,before:page.olderBefore});assert.equal(older.messages.length,50);assert.equal(older.readThrough,null)
      assert(!older.messages.some(row=>page.messages.some(one=>one.id===row.id)))
      await assert.rejects(call('thread',{actor:'coach',id:1}),/denied/)
      await assert.rejects(call('thread',{id:1,version:1}),/denied/)
      await db.exec(`update profiles set active=false where id='${other}'`)
      await assert.rejects(call('list',{actor:'other'}),/denied/)
      for(const role of ['anon','authenticated']){
        await db.exec(`set role ${role}`)
        await assert.rejects(call('list'),/permission denied/)
        await assert.rejects(db.query('select * from app_feedback_messages'),/permission denied/)
        await assert.rejects(db.query('select * from app_feedback_reads'),/permission denied/)
        await assert.rejects(db.query('select * from app_feedback'),/permission denied/)
        await db.exec('reset role')
      }
      await db.exec('set role service_role');assert.equal((await call('thread',{id:1})).messages.length,50);assert.equal((await db.query('select count(*)::integer as n from app_feedback')).rows[0].n,70);await db.exec('reset role')
    })
    await t.test('messages are bounded, repeated IDs do not use quota, and rate limits apply across threads',async()=>{
      await db.exec(`update profiles set active=true where id='${other}'`)
      for(const content of ['', ' ', 'x'.repeat(1001)])await assert.rejects(call('send',{actor:'other',id:2,requestId:randomUUID(),content}),/Invalid feedback/)
      const requestId=randomUUID(),content='x'.repeat(1000)
      await call('send',{actor:'other',id:2,requestId,content})
      for(let i=0;i<9;i++)await call('send',{actor:'other',id:2,requestId:randomUUID(),content:'Följdsvar'})
      assert.equal((await call('send',{actor:'other',id:2,requestId,content})).created,false)
      await assert.rejects(call('send',{actor:'other',id:4,requestId:randomUUID(),content:'För många'}),/rate limit/)
    })
  }finally{await db.close()}
})
