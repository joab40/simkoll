create index community_posts_created_idx on public.community_posts (created_at desc) where deleted_at is null;
create index kudos_created_idx on public.kudos (created_at desc);
create index kudos_sender_date_idx on public.kudos (sender_profile_id, created_at desc);
create index point_events_profile_idx on public.point_events (profile_id, created_at desc);

alter table public.community_posts enable row level security;
